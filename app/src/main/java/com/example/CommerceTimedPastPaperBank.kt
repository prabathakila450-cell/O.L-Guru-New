  private fun cleanDoubleEntrySpecs(limit: Int): List<TimedMcqSpec> {
    val allChallenges = ArrayList<DoubleEntryChallenge>(1600)
    for (batchNum in 1..CommerceDoubleEntryRepository.TOTAL_BATCHES) {
      allChallenges.addAll(CommerceDoubleEntryRepository.getBatch(batchNum).challenges)
    }
    val distinctPairs = allChallenges
      .map { "${TimedPastPaperQualityHelper.sanitizeOption(it.debitAccount)} / ${TimedPastPaperQualityHelper.sanitizeOption(it.creditAccount)}" }
      .distinct()

    val result = ArrayList<TimedMcqSpec>(limit)
    val seenTx = HashSet<String>()
    // Sample with stride so transactions span different accounting categories evenly
    val stepBatch = (allChallenges.size / limit).coerceAtLeast(1)
    for (idx in allChallenges.indices step stepBatch) {
      if (result.size >= limit) break
      val item = allChallenges[idx]
      val cleanTx = item.transaction.replace(Regex("^\\d+\\.\\s*"), "").trim()
      if (cleanTx.length < 15) continue
      val debit = TimedPastPaperQualityHelper.sanitizeOption(item.debitAccount)
      val credit = TimedPastPaperQualityHelper.sanitizeOption(item.creditAccount)
      val correctPair = "$debit / $credit"
      val reversedPair = "${credit.replace(" - බැර", " - හර")} / ${debit.replace(" - හර", " - බැර")}"
      val distractors = ArrayList<String>(3)
      if (reversedPair != correctPair) distractors.add(reversedPair)
      var step = 11
      while (distractors.size < 3 && step < distinctPairs.size) {
        val cand = distinctPairs[(idx + step) % distinctPairs.size]
        if (cand != correctPair && !distractors.contains(cand)) {
          distractors.add(cand)
        }
        step += 17
      }
      if (distractors.size < 3) continue
      val stem = "ව්‍යාපාර ගනුදෙනුවක් වන \"$cleanTx\" යන්න සඳහා නිවැරදි හර සහ බැර ද්විත්ව සටහන කුමක්ද?"
      val opts = listOf(correctPair, distractors[0], distractors[1], distractors[2])
      if (TimedPastPaperQualityHelper.isCleanAndBalanced(stem, opts, 0, item.explanation, isEnglish = false) &&
        seenTx.add(stem.lowercase())
      ) {
        result.add(
          TimedMcqSpec(
            topic = "ද්විත්ව සටහන් මූලධර්මය",
            questionText = stem,
            options = opts,
            correctIndex = 0,
            explanation = item.explanation
          )
        )
      }
    }
    return result
  }
