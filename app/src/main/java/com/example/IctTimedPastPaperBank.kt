          "දශම සංඛ්‍යාවක් වන ${d}₁₀ ෂඩ්දශමය (Hexadecimal) පද්ධතියෙන් ලියූ විට කුමක්ද?",
          "(${hex})₁₆", "(${extras[0]})₁₆", "(${extras[1]})₁₆", "(${extras[2]})₁₆",
          "$d අගය 16න් බෙදා ශේෂ ගත් විට (${hex})₁₆ ලැබේ."
        )
      )
    }

    // 4. Decimal -> Octal (42 values: 75..116)
    for (d in 75..116) {
      val oct = Integer.toOctalString(d)
      val extras = listOf(d + 1, d - 1, d + 2, d + 5)
        .map { Integer.toOctalString(it) }
        .filter { it != oct }.distinct().take(3)
      list.add(
        q(
          "සංඛ්‍යා පද්ධති - අෂ්ටමය",
          "දශම සංඛ්‍යාවක් වන ${d}₁₀ අෂ්ටමය (Octal) පද්ධතියෙන් දැක්වූ විට ලැබෙන්නේ කුමක්ද?",
          "(${oct})₈", "(${extras[0]})₈", "(${extras[1]})₈", "(${extras[2]})₈",
          "$d අගය 8න් බෙදා ශේෂ ගත් විට (${oct})₈ ලැබේ."
        )
      )
    }

    // 5. Data Storage & Capacity calculations (42 distinct)
    for (k in 1..21) {
      val kb = k * 2
      list.add(
        q(
          "දත්ත ගබඩා ධාරිතාව",
          "පරිගණක ගොනුවක ප්‍රමාණය ${kb} KB නම්, එහි අඩංගු බයිට් (Bytes) ගණන කොපමණද?",
          "${kb * 1024} Bytes", "${kb * 1000} Bytes", "${kb * 512} Bytes", "${kb * 2048} Bytes",
          "1 KB = 1024 Bytes බැවින් ${kb} × 1024 = ${kb * 1024} Bytes වේ."
        )
      )
    }
    for (m in 1..21) {
      val gb = m * 3
      list.add(
        q(
          "දත්ත ගබඩා ධාරිතාව",
          "මතක ධාරිතාව ${gb} GB යනු මෙගාබයිට් (MB) කීයකට සමානද? (1 GB = 1024 MB)",
          "${gb * 1024} MB", "${gb * 1000} MB", "${gb * 512} MB", "${gb * 2048} MB",
          "${gb} GB = ${gb} × 1024 = ${gb * 1024} MB."
        )
      )
    }

    // 6. Logic Gates & Boolean Expressions (49 distinct, balanced concise options)
    val ctxWords = listOf(
      "ඩිජිටල් පරිපථයක", "තර්ක ගේට්ටු පද්ධතියක", "තර්ක ඒකකයක", "සංවේදක පාලකයක",
      "ස්වයංක්‍රීය අගුලක", "තාර්කික පුවරුවක", "තර්ක සැලසුමක"
    )
    for (i in 0..48) {
      val a = (i shr 2) and 1
      val b = (i shr 1) and 1
      val c = i and 1
      val mode = i / 7
      val (expr, res) = when (mode) {
        0 -> "(A AND B) OR C" to ((a and b) or c)
        1 -> "(A OR B) AND C" to ((a or b) and c)
        2 -> "NOT(A AND B) OR C" to (((a and b) xor 1) or c)
        3 -> "(A XOR B) AND C" to ((a xor b) and c)
        4 -> "NOT(A OR B) AND (NOT C)" to (((a or b) xor 1) and (c xor 1))
        5 -> "(NOT A) AND (B OR C)" to ((a xor 1) and (b or c))
        else -> "(A NOR B) XOR C" to (((a or b) xor 1) xor c)
      }
      val wrongBit = if (res == 1) 0 else 1
      val vars = when ((i / 7) % 3) {
        0 -> Triple("A", "B", "C")
        1 -> Triple("X", "Y", "Z")
        else -> Triple("P", "Q", "R")
      }
      val customExpr = expr.replace("A", vars.first).replace("B", vars.second).replace("C", vars.third)
      list.add(
        q(
          "තර්ක ද්වාර",
          "${ctxWords[i % ctxWords.size]} ${vars.first}=$a, ${vars.second}=$b සහ ${vars.third}=$c නම් '$customExpr' හි ප්‍රතිදානය කුමක්ද?",
          "$res (${if (res == 1) "HIGH" else "LOW"})",
          "$wrongBit (${if (wrongBit == 1) "HIGH" else "LOW"})",
          "අනිර්ණිත තත්වය",
          "පරිපථ දෝෂය",
          "${vars.first}=$a, ${vars.second}=$b, ${vars.third}=$c ආදේශ කළ විට $customExpr හි ප්‍රතිදානය $res වේ."
        )
      )
    }

    // 7. Spreadsheets & Programming calculations (49 distinct)
    for (i in 1..49) {
      val x = 10 + i
      val y = 20 + i
      val z = 30 + i
      when (i % 4) {
        0 -> list.add(
          q(
            "පැතුරුම්පත්",
            "Excel හි A1=$x, A2=$y, A3=$z නම් =SUM(A1:A3) සූත්‍රය මගින් ලැබෙන අගය කීයද?",
            "${x + y + z}", "${(x + y + z) / 3}", "$z", "${x + y}",
            "SUM(A1:A3) = $x + $y + $z = ${x + y + z}."
          )
        )
        1 -> list.add(
          q(
            "පැතුරුම්පත්",
            "Excel හි B1=$x, B2=$y, B3=$z නම් =AVERAGE(B1:B3) ශ්‍රිතයේ ප්‍රතිදානය කීයද?",
            "${(x + y + z) / 3}", "${x + y + z}", "$x", "$z",
            "AVERAGE(B1:B3) = ($x + $y + $z) / 3 = ${(x + y + z) / 3}."
          )
        )
        2 -> list.add(
          q(
            "පැතුරුම්පත්",
            "Excel හි C1=$x, C2=${z + 15}, C3=$y නම් =MAX(C1:C3) - MIN(C1:C3) හි අගය කීයද?",
            "${(z + 15) - x}", "${z + 15}", "$x", "${y - x}",
            "MAX = ${z + 15}, MIN = $x. වෙනස = ${(z + 15) - x}."
          )
        )
        else -> list.add(
          q(
            "ක්‍රමලේඛනය",
            "Python කේතයේ a = $x; b = ${x + 5}; print(a * 2 + b) ක්‍රියාත්මක කළ විට ප්‍රතිදානය කුමක්ද?",
            "${x * 2 + x + 5}", "${x + x + 5}", "${x * 3}", "${x * 2}",
            "($x × 2) + ${x + 5} = ${x * 2 + x + 5}."
          )
        )
      }
    }

    return list
  }
