      id = qNum,
      topic = spec.topic,
      questionText = spec.questionText,
      correct = spec.correct,
      distractors = spec.distractors,
      explanation = spec.explanation,
      seed = cleanTerm * 10000 + paperIdx * 100 + qNum
    )
  }

