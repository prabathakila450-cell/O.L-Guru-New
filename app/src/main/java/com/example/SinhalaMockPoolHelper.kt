/**
 * Curated Sinhala Language & Literature O/L Question Pool (Grades 10 & 11).
 * Replaces placeholder "වචනය 1A / සන්ධි 1A" templates with 2,200+ strictly unique Sinhala questions
 * from QuizBankSinhala (100), rich Sinhala Grammar/Orthography/Sandhi/Samasa/Literature MCQs (300+),
