object SinhalaMockPoolHelper {

  private val pool: List<QSpec> by lazy { buildMasterPool() }

  fun getQuestion(grade: String, term: Int, paperIdx: Int, qNum: Int): MockExamQuestion {
    return selectFromMasterPool(pool, grade, term, paperIdx, qNum)
  }

  private fun buildMasterPool(): List<QSpec> {
    val raw = ArrayList<QSpec>(2600)

    // 1. 100 Curated QuizBankSinhala MCQs
    for (setIdx in 1..10) {
      for (qIdx in 1..10) {
        val qq = QuizBankSinhala.getQuestion("10", setIdx, qIdx, qIdx, "සිංහල")
        raw.add(quizQuestionToSpec("සිංහල භාෂාව හා සාහිත්‍යය", qq))
      }
    }

    // 2. Curated Sinhala Grammar, Orthography, Sandhi, Samasa, Proverbs & Literature MCQs (280+)
    raw.addAll(buildCuratedSinhalaGrammarAndLit())

    // 3. SubjectMasterRepository Sinhala multi-angle pool (~1,580 specs)
    raw.addAll(
      buildPoolFromSubjectMaster(
        categories = SubjectMasterRepository.getCategoriesForSubject("සිංහල"),
        subjectLabel = "සිංහල",
        seedBase = 37
      )
    )

    // 4. ShortAnswerMasterRepository Grade 10 & Grade 11 Sinhala (~400 specs)
    raw.addAll(buildPoolFromShortAnswers("සිංහල"))

    return dedupPool(raw)
  }

